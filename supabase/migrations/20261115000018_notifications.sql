-- Notifications (in-app bell and a daily email digest) and @mentions in task comments.
-- Notifications are created only by database triggers and the daily reminder job, never by the browser.

create table public.notifications (
  id          bigint generated by default as identity primary key,
  profile_id  uuid not null references public.profiles(id) on delete cascade,
  kind        text not null,
  title       text not null,
  body        text,
  href        text,
  actor_id    uuid references public.profiles(id) on delete set null,
  dedupe_key  text,
  created_at  timestamptz not null default now(),
  read_at     timestamptz,
  emailed_at  timestamptz
);
create unique index notifications_dedupe on public.notifications (profile_id, dedupe_key) where dedupe_key is not null;
create index on public.notifications (profile_id, created_at desc);
create index notifications_unread on public.notifications (profile_id) where read_at is null;
alter table public.notifications enable row level security;
grant select on public.notifications to authenticated;
create policy "notifications read own" on public.notifications for select to authenticated using (profile_id = auth.uid());

create table public.notification_prefs (
  profile_id    uuid primary key references public.profiles(id) on delete cascade,
  email_enabled boolean not null default true
);
alter table public.notification_prefs enable row level security;
grant select on public.notification_prefs to authenticated;
create policy "prefs read own" on public.notification_prefs for select to authenticated using (profile_id = auth.uid());

alter table public.task_comments add column mentions uuid[] not null default '{}';

-- ------------------------------------------------------------------ internal helpers
create or replace function public._person_name(p uuid) returns text
language sql stable security definer set search_path = '' as $$ select coalesce((select name from public.profiles where id = p), 'Someone') $$;

-- Could this person open the task? (same rules as can_see_task, for any person rather than the caller)
create or replace function public._person_sees_task(p_profile uuid, p_task bigint) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles pr where pr.id = p_profile and pr.active and (
      pr.role = 'admin'
      or exists (select 1 from public.tasks t where t.id = p_task and (t.created_by = p_profile
           or (t.project_id is not null and (pr.role in ('bd','teamlead','teamlead2')
                or exists (select 1 from public.project_team m where m.project_id = t.project_id and m.member_id = p_profile)
                or exists (select 1 from public.projects x where x.id = t.project_id and x.leader_id = p_profile)))))
      or exists (select 1 from public.task_participants tp where tp.task_id = p_task and tp.profile_id = p_profile)))
$$;

create or replace function public._notify(p_to uuid, p_kind text, p_title text, p_body text, p_href text, p_actor uuid default null, p_key text default null)
returns boolean language plpgsql security definer set search_path = '' as $$
declare v_id bigint;
begin
  if p_to is null or p_to is not distinct from p_actor then return false; end if;
  if not exists (select 1 from public.profiles where id = p_to and active) then return false; end if;
  insert into public.notifications (profile_id, kind, title, body, href, actor_id, dedupe_key)
  values (p_to, p_kind, left(p_title, 200), left(p_body, 300), p_href, p_actor, p_key)
  on conflict (profile_id, dedupe_key) where dedupe_key is not null do nothing
  returning id into v_id;
  return v_id is not null;
end $$;
revoke all on function public._person_name(uuid), public._person_sees_task(uuid, bigint),
  public._notify(uuid, text, text, text, text, uuid, text) from public, anon, authenticated;

-- ------------------------------------------------------------------ triggers
create or replace function public._trg_task_assigned() returns trigger
language plpgsql security definer set search_path = '' as $$
declare t record;
begin
  select id, title into t from public.tasks where id = new.task_id;
  perform public._notify(new.profile_id, 'task_assigned',
    case when new.is_responsible then public._person_name(auth.uid()) || ' gave you a task' else public._person_name(auth.uid()) || ' added you to a task' end,
    t.title, '/tasks/' || t.id, auth.uid());
  return new;
end $$;
create trigger task_assigned after insert on public.task_participants for each row execute function public._trg_task_assigned();

create or replace function public._trg_task_comment() returns trigger
language plpgsql security definer set search_path = '' as $$
declare t record; r uuid; who text := public._person_name(new.user_id);
begin
  select id, title, created_by into t from public.tasks where id = new.task_id;
  -- people mentioned (only those who can open the task)
  foreach r in array new.mentions loop
    if public._person_sees_task(r, t.id) then
      perform public._notify(r, 'mention', who || ' mentioned you', t.title || ': ' || new.comment, '/tasks/' || t.id, new.user_id);
    end if;
  end loop;
  -- everyone else on the task
  for r in select distinct x from (select t.created_by as x union select profile_id from public.task_participants where task_id = t.id) q
            where x is not null and x <> all (new.mentions) loop
    perform public._notify(r, 'task_comment', who || ' commented', t.title || ': ' || new.comment, '/tasks/' || t.id, new.user_id);
  end loop;
  return new;
end $$;
create trigger task_comment_notify after insert on public.task_comments for each row execute function public._trg_task_comment();

create or replace function public._trg_leave() returns trigger
language plpgsql security definer set search_path = '' as $$
declare a uuid;
begin
  if tg_op = 'INSERT' then
    for a in select id from public.profiles where role = 'admin' and active loop
      perform public._notify(a, 'leave_request', public._person_name(new.profile_id) || ' applied for leave',
        new.leave_type || ', ' || to_char(new.leave_from, 'DD Mon') || ' to ' || to_char(new.leave_to, 'DD Mon'), '/hr/leave', new.profile_id);
    end loop;
  elsif new.status is distinct from old.status and new.status in ('approved', 'rejected') then
    perform public._notify(new.profile_id, 'leave_decision', 'Your leave was ' || new.status,
      new.leave_type || ', ' || to_char(new.leave_from, 'DD Mon') || ' to ' || to_char(new.leave_to, 'DD Mon'), '/hr/leave', new.changed_by);
  end if;
  return new;
end $$;
create trigger leave_notify after insert or update of status on public.leave_applications for each row execute function public._trg_leave();

create or replace function public._trg_time_edit() returns trigger
language plpgsql security definer set search_path = '' as $$
declare a uuid; who uuid := auth.uid();
begin
  for a in select id from public.profiles where role = 'admin' and active loop
    perform public._notify(a, 'time_edit_request', public._person_name(who) || ' asked to change a time entry', null, '/time-tracker/approvals', who);
  end loop;
  return new;
end $$;
create trigger time_edit_notify after insert on public.time_entry_edits for each row execute function public._trg_time_edit();

create or replace function public._trg_project_pending() returns trigger
language plpgsql security definer set search_path = '' as $$
declare a uuid;
begin
  if new.status = 'pending' then
    for a in select id from public.profiles where role = 'admin' and active loop
      perform public._notify(a, 'project_pending', 'A project is waiting for approval', new.name, '/projects/pending', auth.uid());
    end loop;
  end if;
  return new;
end $$;
create trigger project_pending_notify after insert on public.projects for each row execute function public._trg_project_pending();

create or replace function public._trg_appraisal_published() returns trigger
language plpgsql security definer set search_path = '' as $$
declare r uuid;
begin
  if old.published_at is null and new.published_at is not null then
    for r in select profile_id from public.appraisal_results where cycle_id = new.id loop
      perform public._notify(r, 'appraisal_published', 'Your appraisal is ready', new.name, '/hr/appraisal/' || r, auth.uid());
    end loop;
  end if;
  return new;
end $$;
create trigger appraisal_published_notify after update of published_at on public.appraisal_cycles for each row execute function public._trg_appraisal_published();

-- ------------------------------------------------------------------ what the signed-in person can do
create or replace function public.mark_notification_read(p_id bigint) returns void
language sql security definer set search_path = '' as $$
  update public.notifications set read_at = coalesce(read_at, now()) where id = p_id and profile_id = auth.uid();
$$;
create or replace function public.mark_all_notifications_read() returns void
language sql security definer set search_path = '' as $$
  update public.notifications set read_at = now() where profile_id = auth.uid() and read_at is null;
$$;
create or replace function public.set_email_notifications(p_on boolean) returns void
language sql security definer set search_path = '' as $$
  insert into public.notification_prefs (profile_id, email_enabled) values (auth.uid(), p_on)
  on conflict (profile_id) do update set email_enabled = excluded.email_enabled;
$$;
grant execute on function public.mark_notification_read(bigint), public.mark_all_notifications_read(), public.set_email_notifications(boolean) to authenticated;

-- ------------------------------------------------------------------ daily job (service role only)
-- Returns how many new reminders were created. Reminders for open tasks: the day before, on the due date, and 1, 3 and 7 days late. One per person per task per day.
create or replace function public.generate_due_notifications() returns integer
language plpgsql security definer set search_path = '' as $$
declare v_today date := (now() at time zone 'Asia/Kolkata')::date; n integer := 0; r record; late integer;
begin
  for r in select t.id, t.title, t.ends_on, tp.profile_id from public.tasks t join public.task_participants tp on tp.task_id = t.id and tp.is_responsible
            where t.status = 'created' and t.ends_on is not null and (v_today - t.ends_on) in (-1, 0, 1, 3, 7) loop
    late := v_today - r.ends_on;
    if public._notify(r.profile_id, 'task_due',
      case when late = -1 then 'Due tomorrow' when late = 0 then 'Due today' else 'Overdue by ' || late || ' day' || case when late = 1 then '' else 's' end end,
      r.title, '/tasks/' || r.id, null, 'due:' || r.id || ':' || v_today) then n := n + 1; end if;
  end loop;
  return n;
end $$;
revoke all on function public.generate_due_notifications() from public, anon, authenticated;
do $$ begin if exists (select 1 from pg_roles where rolname = 'service_role') then grant execute on function public.generate_due_notifications() to service_role; end if; end $$;

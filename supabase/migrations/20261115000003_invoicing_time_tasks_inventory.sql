-- --------------------------------------------------------------------- invoicing
create table public.sac_codes (
  id           bigint generated by default as identity primary key,
  sac          text not null,
  description  text not null,
  active       boolean not null default true
);

-- One table for live and deleted invoices (legacy had project_invoice + project_invoice_deleted).
-- Deleted invoices keep deleted_at / deleted_by instead of moving to a second table.
create table public.invoices (
  id               bigint generated by default as identity primary key,
  project_id       bigint references public.projects(id),
  invoice_no       text not null,
  invoice_type     text not null check (invoice_type in ('Proforma','Taxable','Export')),
  invoice_by       text not null default 'MARC',           -- billing entity: MARC, KNP, AC, KNPM
  invoice_by_type  text,                                   -- series: M, Q, Y, MISC
  invoice_date     date,
  place_of_supply  text,
  recipient_name   text,
  recipient_address text,
  recipient_pan    text,
  recipient_gst    text,
  recipient_state_code text,
  delivery_name    text,
  delivery_address text,
  delivery_pan     text,
  delivery_gst     text,
  delivery_state_code text,
  service_description text,
  sac              text,
  taxable_value    numeric(14,2),
  advance          numeric(14,2),
  discount         numeric(14,2),
  ope              numeric(14,2),                          -- out-of-pocket expenses
  currency_type    text,                                   -- null/'' = INR; USD, AED, EUR, GBP, ZAR
  currency_value   numeric(14,4),                          -- conversion rate to INR
  currency_ope     numeric(14,2),
  confirmed        boolean not null default false,
  confirmed_by     uuid references public.profiles(id),
  confirmed_at     timestamptz,
  converted        boolean not null default false,         -- proforma converted to tax invoice
  created_by       uuid references public.profiles(id),
  created_at       timestamptz,
  deleted_by       uuid references public.profiles(id),
  deleted_at       timestamptz
);
create index on public.invoices (project_id);
create index on public.invoices (invoice_by, invoice_no);

-- Atomic, gap-free invoice numbering per entity and financial year (used by invoice creation).
create table public.invoice_counters (
  invoice_by     text not null,
  series         text not null,           -- e.g. 'I-MARC-2026-27' or 'I-PROF-2026-27'
  last_number    integer not null default 0,
  primary key (invoice_by, series)
);

create or replace function public.next_invoice_number(p_entity text, p_series text)
returns integer language plpgsql security definer set search_path = '' as $$
declare n integer;
begin
  insert into public.invoice_counters (invoice_by, series, last_number)
  values (p_entity, p_series, 1)
  on conflict (invoice_by, series)
  do update set last_number = public.invoice_counters.last_number + 1
  returning last_number into n;
  return n;
end $$;

-- ---------------------------------------------------------------- reimbursements
create table public.reimbursement_rates (
  id           bigint generated by default as identity primary key,
  type         text not null,
  price        numeric(10,2) not null,
  active       boolean not null default true
);

create table public.reimbursements (
  id           bigint generated by default as identity primary key,
  project_id   bigint references public.projects(id),
  profile_id   uuid not null references public.profiles(id),
  period_from  date,
  period_to    date,
  distance     numeric(10,2),
  price        numeric(10,2),
  sub_amount   numeric(12,2),
  amount       numeric(12,2) not null,
  description  text,
  non_chargeable_category text,
  status       text not null default 'pending' check (status in ('pending','approved','rejected')),
  added_by     uuid references public.profiles(id),
  added_at     timestamptz,
  approved_by  uuid references public.profiles(id),
  approved_at  timestamptz
);
create index on public.reimbursements (profile_id);
create index on public.reimbursements (project_id);

-- ----------------------------------------------------------------- time tracking
-- Legacy stored client_name / project_name as text, where project_name holds the project id.
-- hours were stored as minutes ("480" = 8 hours), so the column is minutes.
create table public.time_entries (
  id           bigint generated by default as identity primary key,
  profile_id   uuid not null references public.profiles(id),
  entry_date   date not null,
  project_id   bigint references public.projects(id),
  client_name  text,
  project_ref  text,                 -- original value from the legacy project_name column
  work_accomplished text,
  minutes      integer not null check (minutes >= 0),
  non_chargeable_category text,      -- empty = chargeable
  remarks      text not null default '-',
  submitted_at timestamptz
);
create index on public.time_entries (profile_id, entry_date);
create index on public.time_entries (project_id);
create index on public.time_entries (entry_date);

-- Pending edits to an entry, awaiting approval (legacy time_tracker_temp).
create table public.time_entry_edits (
  id           bigint generated by default as identity primary key,
  time_entry_id bigint references public.time_entries(id) on delete cascade,
  profile_id   uuid not null references public.profiles(id),
  entry_date   date,
  client_name  text,
  project_ref  text,
  work_accomplished text,
  minutes      integer,
  non_chargeable_category text,
  remarks      text,
  submitted_at timestamptz
);

-- ------------------------------------------------------------------------ tasks
-- One tasks table: project_id null = general task, set = project task
-- (legacy had tasks + project_tasks and two comment tables).
create table public.tasks (
  id           bigint generated by default as identity primary key,
  project_id   bigint references public.projects(id) on delete cascade,
  title        text not null,
  description  text,
  starts_on    date,
  ends_on      date,
  status       text not null default 'created' check (status in ('created','completed')),
  created_by   uuid references public.profiles(id),
  created_at   timestamptz,
  completed_at timestamptz,
  edited_by    uuid references public.profiles(id),
  edited_at    timestamptz
);
create index on public.tasks (project_id);

create table public.task_participants (
  task_id      bigint not null references public.tasks(id) on delete cascade,
  profile_id   uuid not null references public.profiles(id),
  is_responsible boolean not null default false,
  primary key (task_id, profile_id)
);
create index on public.task_participants (profile_id);

create table public.task_comments (
  id           bigint generated by default as identity primary key,
  task_id      bigint not null references public.tasks(id) on delete cascade,
  user_id      uuid references public.profiles(id),
  comment      text not null,
  created_at   timestamptz
);
create index on public.task_comments (task_id);


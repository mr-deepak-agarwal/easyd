-- Phase 8b: appraisal cycles. A cycle freezes every employee's score for a period, admin adds a final
-- rating and remark, publishes it, and the employee reads and acknowledges it.

create table public.appraisal_cycles (
  id           bigint generated by default as identity primary key,
  name         text not null,
  period_from  date not null,
  period_to    date not null check (period_to >= period_from),
  status       text not null default 'open' check (status in ('open','closed')),
  published_at timestamptz,
  created_by   uuid references public.profiles(id),
  created_at   timestamptz not null default now(),
  closed_at    timestamptz
);
create table public.appraisal_results (
  id               bigint generated by default as identity primary key,
  cycle_id         bigint not null references public.appraisal_cycles(id) on delete cascade,
  profile_id       uuid not null references public.profiles(id),
  total            numeric(5,1),
  band             text,
  parts            jsonb not null default '[]',   -- score and explanation of each measure when the cycle closed
  weights          jsonb not null default '{}',
  review_count     integer not null default 0,
  final_rating     smallint check (final_rating between 1 and 5),
  admin_remark     text,
  rated_by         uuid references public.profiles(id),
  rated_at         timestamptz,
  employee_comment text,
  acknowledged_at  timestamptz,
  unique (cycle_id, profile_id)
);
create index on public.appraisal_results (profile_id);
alter table public.appraisal_cycles enable row level security;
alter table public.appraisal_results enable row level security;
grant select on public.appraisal_cycles, public.appraisal_results to authenticated;
create policy "cycles read" on public.appraisal_cycles for select to authenticated
  using (public.is_admin() or published_at is not null);
create policy "results read" on public.appraisal_results for select to authenticated
  using (public.is_admin() or (profile_id = auth.uid() and exists (select 1 from public.appraisal_cycles c where c.id = cycle_id and c.published_at is not null)));

create or replace function public.create_appraisal_cycle(p_name text, p_from date, p_to date)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_id bigint;
begin
  if not public.is_admin() then raise exception 'Only an admin can run appraisal cycles'; end if;
  if coalesce(trim(p_name),'') = '' then raise exception 'Enter a name for the cycle'; end if;
  if p_from is null or p_to is null or p_to < p_from then raise exception 'Enter a valid period'; end if;
  insert into public.appraisal_cycles (name, period_from, period_to, created_by) values (trim(p_name), p_from, p_to, auth.uid()) returning id into v_id;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'appraisal.cycle.create', 'appraisal_cycles', v_id::text);
  return v_id;
end $$;

-- p_results: [{profile_id, total, band, parts, weights, review_count}, ...] worked out by the app from employee_scorecard()
create or replace function public.close_appraisal_cycle(p_cycle bigint, p_results jsonb)
returns integer language plpgsql security definer set search_path = '' as $$
declare r jsonb; n integer := 0;
begin
  if not public.is_admin() then raise exception 'Only an admin can run appraisal cycles'; end if;
  if not exists (select 1 from public.appraisal_cycles where id = p_cycle and status = 'open') then raise exception 'This cycle is already closed'; end if;
  if p_results is null or jsonb_typeof(p_results) <> 'array' then raise exception 'No results to save'; end if;
  for r in select * from jsonb_array_elements(p_results) loop
    insert into public.appraisal_results (cycle_id, profile_id, total, band, parts, weights, review_count)
    values (p_cycle, (r->>'profile_id')::uuid, nullif(r->>'total','')::numeric, nullif(r->>'band',''), coalesce(r->'parts','[]'), coalesce(r->'weights','{}'), coalesce((r->>'review_count')::int, 0))
    on conflict (cycle_id, profile_id) do nothing;
    n := n + 1;
  end loop;
  update public.appraisal_cycles set status = 'closed', closed_at = now() where id = p_cycle;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'appraisal.cycle.close', 'appraisal_cycles', p_cycle::text);
  return n;
end $$;

create or replace function public.rate_appraisal_result(p_result bigint, p_rating integer, p_remark text)
returns void language plpgsql security definer set search_path = '' as $$
declare x public.appraisal_results;
begin
  if not public.is_admin() then raise exception 'Only an admin can rate appraisals'; end if;
  if p_rating is null or p_rating < 1 or p_rating > 5 then raise exception 'The final rating must be from 1 to 5'; end if;
  select * into x from public.appraisal_results where id = p_result for update;
  if not found then raise exception 'Result not found'; end if;
  if x.acknowledged_at is not null then raise exception 'The employee has already acknowledged this result'; end if;
  update public.appraisal_results set final_rating = p_rating, admin_remark = nullif(trim(p_remark),''), rated_by = auth.uid(), rated_at = now() where id = p_result;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'appraisal.rate', 'appraisal_results', p_result::text);
end $$;

create or replace function public.publish_appraisal_cycle(p_cycle bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then raise exception 'Only an admin can publish appraisals'; end if;
  if exists (select 1 from public.appraisal_results where cycle_id = p_cycle and final_rating is null and total is not null) then
    raise exception 'Give every employee a final rating before publishing'; end if;
  update public.appraisal_cycles set published_at = now() where id = p_cycle and status = 'closed' and published_at is null;
  if not found then raise exception 'Close the cycle first, or it is already published'; end if;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'appraisal.publish', 'appraisal_cycles', p_cycle::text);
end $$;

create or replace function public.acknowledge_appraisal(p_result bigint, p_comment text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  update public.appraisal_results r set employee_comment = nullif(trim(p_comment),''), acknowledged_at = now()
   where r.id = p_result and r.profile_id = auth.uid() and r.acknowledged_at is null
     and exists (select 1 from public.appraisal_cycles c where c.id = r.cycle_id and c.published_at is not null);
  if not found then raise exception 'This result cannot be acknowledged'; end if;
end $$;

grant execute on function public.create_appraisal_cycle(text,date,date), public.close_appraisal_cycle(bigint,jsonb),
  public.rate_appraisal_result(bigint,integer,text), public.publish_appraisal_cycle(bigint), public.acknowledge_appraisal(bigint,text) to authenticated;

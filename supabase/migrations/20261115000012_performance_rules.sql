-- Phase 8: employee performance scorecards.
-- A score is built from what the employee logs in the ERP: tasks and milestones finished on time,
-- time logged on the projects they are assigned to, attendance, and reviews written by team leads.

-- 1) Milestones know who owns them and when they were really finished.
alter table public.project_milestones
  add column if not exists owner_id uuid references public.profiles(id),
  add column if not exists completed_at timestamptz;
update public.project_milestones set completed_at = coalesce(updated_at, created_at) where complete and completed_at is null;

create or replace function public.milestone_completed_stamp() returns trigger language plpgsql set search_path = '' as $$
begin
  if new.complete and not coalesce(old.complete, false) then new.completed_at := now();
  elsif not new.complete then new.completed_at := null; end if;
  return new;
end $$;
create trigger milestone_completed_stamp before update on public.project_milestones
  for each row execute function public.milestone_completed_stamp();

-- 2) Team lead reviews of an employee's work on a project (1 = poor ... 5 = excellent).
create table public.performance_reviews (
  id             bigint generated by default as identity primary key,
  profile_id     uuid not null references public.profiles(id),
  project_id     bigint not null references public.projects(id) on delete cascade,
  reviewer_id    uuid not null references public.profiles(id),
  review_month   date not null,                       -- first day of the month the review is for
  followup       smallint not null check (followup   between 1 and 5),   -- feedback and follow-up
  ownership      smallint not null check (ownership  between 1 and 5),   -- ownership of the project
  accuracy       smallint not null check (accuracy   between 1 and 5),   -- formatting and accuracy
  enthusiasm     smallint not null check (enthusiasm between 1 and 5),
  detail         smallint not null check (detail     between 1 and 5),   -- attention to detail
  comments       text,
  created_at     timestamptz not null default now(),
  unique (profile_id, project_id, reviewer_id, review_month)
);
create index on public.performance_reviews (profile_id, review_month);
alter table public.performance_reviews enable row level security;
grant select on public.performance_reviews to authenticated;
create policy "reviews read" on public.performance_reviews for select to authenticated
  using (profile_id = auth.uid() or reviewer_id = auth.uid() or public.has_role('admin','teamlead2'));
-- written only through submit_review(); admin can remove one
create policy "reviews admin delete" on public.performance_reviews for delete to authenticated using (public.is_admin());
grant delete on public.performance_reviews to authenticated;

create or replace function public.submit_review(p_profile uuid, p_project bigint, p_followup int, p_ownership int,
  p_accuracy int, p_enthusiasm int, p_detail int, p_comments text)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_id bigint; v_month date := date_trunc('month', (now() at time zone 'Asia/Kolkata'))::date;
begin
  if not public.has_role('admin','teamlead','teamlead2') then raise exception 'Only team leads and admins can review work'; end if;
  if p_profile = auth.uid() then raise exception 'You cannot review your own work'; end if;
  if not public.can_manage_project(p_project) then raise exception 'You can only review people on projects you manage'; end if;
  if not exists (select 1 from public.projects where id = p_project and status in ('approved','closed')) then raise exception 'That project is not open'; end if;
  if not exists (select 1 from public.project_team where project_id = p_project and member_id = p_profile) then raise exception 'That person is not on this project''s team'; end if;
  if least(p_followup,p_ownership,p_accuracy,p_enthusiasm,p_detail) < 1 or greatest(p_followup,p_ownership,p_accuracy,p_enthusiasm,p_detail) > 5 then
    raise exception 'Every rating must be from 1 to 5'; end if;
  insert into public.performance_reviews (profile_id, project_id, reviewer_id, review_month, followup, ownership, accuracy, enthusiasm, detail, comments)
  values (p_profile, p_project, auth.uid(), v_month, p_followup, p_ownership, p_accuracy, p_enthusiasm, p_detail, nullif(trim(p_comments),''))
  on conflict (profile_id, project_id, reviewer_id, review_month) do update
    set followup = excluded.followup, ownership = excluded.ownership, accuracy = excluded.accuracy,
        enthusiasm = excluded.enthusiasm, detail = excluded.detail, comments = excluded.comments, created_at = now()
  returning id into v_id;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'review.submit', 'performance_reviews', v_id::text);
  return v_id;
end $$;

-- 3) Weights of the score (admin sets them; they must add up to 100).
create table public.score_weights (
  key     text primary key,
  label   text not null,
  weight  numeric(5,2) not null check (weight between 0 and 100),
  sort    integer not null
);
insert into public.score_weights (key, label, weight, sort) values
  ('ontime',     'Tasks and milestones on time',        25, 1),
  ('discipline', 'Time logged on days worked',          20, 2),
  ('match',      'Time logged on assigned projects',    15, 3),
  ('attendance', 'Attendance',                          10, 4),
  ('reviews',    'Team lead reviews',                   30, 5);
alter table public.score_weights enable row level security;
grant select on public.score_weights to authenticated;
create policy "weights read" on public.score_weights for select to authenticated using (true);

create or replace function public.set_score_weights(p_weights jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare k text; v numeric; total numeric := 0;
begin
  if not public.is_admin() then raise exception 'Only an admin can change the weights'; end if;
  for k in select key from public.score_weights loop
    v := (p_weights->>k)::numeric;
    if v is null or v < 0 or v > 100 then raise exception 'Enter a weight from 0 to 100 for every part'; end if;
    total := total + v;
  end loop;
  if total <> 100 then raise exception 'The weights must add up to 100 (they add up to %)', total; end if;
  for k in select key from public.score_weights loop
    update public.score_weights set weight = (p_weights->>k)::numeric where key = k;
  end loop;
  insert into public.audit_log (actor_id, action, entity, details) values (auth.uid(), 'score.weights', 'score_weights', p_weights);
end $$;

-- 4) The raw numbers behind a scorecard. Scores and the weighted total are worked out in the app.
--    Working days: Mon-Sat, minus holidays and approved full-day CL / PL / Compensatory Off / Optional Holiday.
--    Present: an attendance row other than 'A', or an approved OD / Work From Home leave.
--    Only things already due (up to today) are judged.
create or replace function public.employee_scorecard(p_profile uuid, p_from date, p_to date, p_full_day_minutes integer default 360)
returns table (
  tasks_due integer, tasks_on_time integer, milestones_due integer, milestones_on_time integer,
  working_days integer, attendance_rows integer, present_days integer, logged_days integer,
  assigned_minutes bigint, unassigned_minutes bigint, nonchargeable_minutes bigint, idle_projects integer,
  review_count integer, review_avg numeric
) language plpgsql security definer stable set search_path = '' as $$
declare v_to date := least(p_to, (now() at time zone 'Asia/Kolkata')::date);
begin
  if not (p_profile = auth.uid() or public.has_role('admin','teamlead','teamlead2')) then raise exception 'Not allowed'; end if;
  return query
  with days as (
    select d::date as d from generate_series(p_from, v_to, interval '1 day') d
     where extract(dow from d) <> 0
       and not exists (select 1 from public.holidays h where h.holiday_date = d::date)
       and not exists (select 1 from public.leave_applications l where l.profile_id = p_profile and l.status = 'approved'
             and d::date between l.leave_from and l.leave_to
             and l.leave_type in ('CL Full Day','PL Full Day','Compensatory Off','Optional Holiday'))
  ), pres as (
    select dd.d from days dd
     where exists (select 1 from public.attendance a where a.profile_id = p_profile and a.work_date = dd.d and coalesce(a.status,'') <> 'A')
        or exists (select 1 from public.leave_applications l where l.profile_id = p_profile and l.status = 'approved'
             and dd.d between l.leave_from and l.leave_to and l.leave_type in ('OD Full Day','OD Half Day','Work From Home'))
  ), t as (
    select tk.* from public.tasks tk join public.task_participants tp on tp.task_id = tk.id and tp.profile_id = p_profile
     where tk.ends_on between p_from and v_to
  ), m as (
    select * from public.project_milestones where owner_id = p_profile and end_date between p_from and v_to
  ), te as (
    select e.* from public.time_entries e where e.profile_id = p_profile and e.entry_date between p_from and p_to
  ), per_day as (
    select entry_date, sum(minutes) as mins from te group by entry_date
  ), assigned as (
    select project_id from public.project_team where member_id = p_profile
  )
  select
    (select count(*) from t)::int,
    (select count(*) from t where status = 'completed' and (completed_at at time zone 'Asia/Kolkata')::date <= ends_on)::int,
    (select count(*) from m)::int,
    (select count(*) from m where complete and (completed_at at time zone 'Asia/Kolkata')::date <= end_date)::int,
    (select count(*) from days)::int,
    (select count(*) from public.attendance a where a.profile_id = p_profile and a.work_date between p_from and p_to)::int,
    (select count(*) from pres)::int,
    (select count(*) from pres pr join per_day pd on pd.entry_date = pr.d where pd.mins >= p_full_day_minutes)::int,
    coalesce((select sum(minutes) from te where project_id in (select project_id from assigned)), 0)::bigint,
    coalesce((select sum(minutes) from te where project_id is not null and project_id not in (select project_id from assigned)), 0)::bigint,
    coalesce((select sum(minutes) from te where project_id is null), 0)::bigint,
    (select count(*) from public.project_team pt join public.projects pj on pj.id = pt.project_id
      where pt.member_id = p_profile and pj.status = 'approved'
        and not exists (select 1 from te where te.project_id = pt.project_id))::int,
    (select count(*) from public.performance_reviews r where r.profile_id = p_profile and r.review_month between date_trunc('month', p_from)::date and p_to)::int,
    (select round(avg((r.followup + r.ownership + r.accuracy + r.enthusiasm + r.detail) / 5.0), 2) from public.performance_reviews r
      where r.profile_id = p_profile and r.review_month between date_trunc('month', p_from)::date and p_to);
end $$;

-- Who is late right now (open items already past their date) for one person.
create or replace function public.employee_overdue(p_profile uuid)
returns table (kind text, title text, project_name text, due date, ref_id bigint)
language plpgsql security definer stable set search_path = '' as $$
declare v_today date := (now() at time zone 'Asia/Kolkata')::date;
begin
  if not (p_profile = auth.uid() or public.has_role('admin','teamlead','teamlead2')) then raise exception 'Not allowed'; end if;
  return query
    select 'Task'::text, tk.title, pj.name, tk.ends_on, tk.id
      from public.tasks tk join public.task_participants tp on tp.task_id = tk.id and tp.profile_id = p_profile
      left join public.projects pj on pj.id = tk.project_id
     where tk.status <> 'completed' and tk.ends_on < v_today
    union all
    select 'Milestone', mi.milestone, pj.name, mi.end_date, mi.project_id
      from public.project_milestones mi join public.projects pj on pj.id = mi.project_id
     where mi.owner_id = p_profile and not mi.complete and mi.end_date < v_today and pj.status = 'approved'
    order by 4;
end $$;

grant execute on function public.submit_review(uuid,bigint,int,int,int,int,int,text), public.set_score_weights(jsonb),
  public.employee_scorecard(uuid,date,date,integer), public.employee_overdue(uuid) to authenticated;

-- Phase 6: invoicing.
-- Legacy stored one row per invoice LINE with the header repeated; the 46 "duplicate" numbers
-- are just multi-line invoices. Split into header (invoices) + invoice_lines.
-- Numbers keep the legacy formats exactly. Uniqueness is deliberately NOT enforced yet
-- (client will clean the data after launch).

alter table public.invoices
  drop column if exists service_description,
  drop column if exists sac,
  drop column if exists taxable_value,
  drop column if exists currency_value;

create table public.invoice_lines (
  id                  bigint generated by default as identity primary key,
  invoice_id          bigint not null references public.invoices(id) on delete cascade,
  position            integer not null default 1,
  service_description text,
  sac                 text,
  taxable_value       numeric(14,2) not null default 0,
  rupee_value         numeric(14,4)          -- legacy currencyvalue: INR value of this line when billed in a foreign currency
);
create index on public.invoice_lines (invoice_id, position);
alter table public.invoice_lines enable row level security;
grant select on public.invoice_lines to authenticated;
create policy "invoice_lines read" on public.invoice_lines for select to authenticated
  using (public.has_role('admin','bd','teamlead2'));
create policy "invoice_lines write" on public.invoice_lines for all to authenticated
  using (public.has_role('admin','teamlead2')) with check (public.has_role('admin','teamlead2'));

-- Legacy number prefix: P-MARC-26-27- | P-AC-26-27- | P-KPC-MH-26-27-M- | P-KPC-MP-26-27-M- | P-KPC-26-27-
create or replace function public.invoice_prefix(p_type text, p_entity text, p_series text, p_fy text)
returns text language sql immutable set search_path = '' as $$
  select case p_type when 'Proforma' then 'P' when 'Taxable' then 'T' else 'E' end || '-' ||
    case p_entity
      when 'MARC' then 'MARC-' || p_fy || '-'
      when 'AC'   then 'AC-' || p_fy || '-'
      when 'KNPM' then 'KPC-MH-' || p_fy || '-' || coalesce(p_series,'') || '-'
      when 'KNPI' then 'KPC-MP-' || p_fy || '-' || coalesce(p_series,'') || '-'
      else 'KPC-' || p_fy || '-'
    end
$$;

-- Financial year starting April, "26-27".
create or replace function public.financial_year(p_date date)
returns text language sql immutable set search_path = '' as $$
  select case when extract(month from p_date) >= 4
    then to_char(p_date,'YY') || '-' || to_char(p_date + interval '1 year','YY')
    else to_char(p_date - interval '1 year','YY') || '-' || to_char(p_date,'YY') end
$$;

-- Next number = highest trailing number among live invoices with the same prefix, + 1.
create or replace function public.next_invoice_no(p_type text, p_entity text, p_series text)
returns text language plpgsql security definer set search_path = '' as $$
declare
  v_fy text := public.financial_year((now() at time zone 'Asia/Kolkata')::date);
  v_prefix text := public.invoice_prefix(p_type, p_entity, p_series, v_fy);
  v_max integer;
begin
  perform pg_advisory_xact_lock(hashtext('invoice_no:' || v_prefix));
  select coalesce(max((substring(invoice_no from '([0-9]+)$'))::integer), 0) into v_max
    from public.invoices
   where deleted_at is null and invoice_by = p_entity and left(invoice_no, length(v_prefix)) = v_prefix;
  return v_prefix || (v_max + 1);
end $$;
revoke all on function public.next_invoice_no(text,text,text) from public, anon, authenticated;

create or replace function public._invoice_guard()
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.has_role('admin','teamlead2') then raise exception 'Not allowed to manage invoices'; end if;
end $$;
revoke all on function public._invoice_guard() from public, anon, authenticated;

create or replace function public._invoice_save_lines(p_invoice bigint, p_lines jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare l jsonb; i integer := 0;
begin
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Add at least one line';
  end if;
  delete from public.invoice_lines where invoice_id = p_invoice;
  for l in select * from jsonb_array_elements(p_lines) loop
    i := i + 1;
    if coalesce((l->>'taxable_value')::numeric, -1) < 0 then raise exception 'Line % needs an amount of 0 or more', i; end if;
    insert into public.invoice_lines (invoice_id, position, service_description, sac, taxable_value, rupee_value)
    values (p_invoice, i, nullif(trim(l->>'service_description'),''), nullif(trim(l->>'sac'),''),
            (l->>'taxable_value')::numeric, nullif(l->>'rupee_value','')::numeric);
  end loop;
end $$;
revoke all on function public._invoice_save_lines(bigint,jsonb) from public, anon, authenticated;

create or replace function public.create_invoice(p_header jsonb, p_lines jsonb)
returns bigint language plpgsql security definer set search_path = '' as $$
declare
  v_type text := p_header->>'invoice_type';
  v_by text := coalesce(nullif(p_header->>'invoice_by',''), 'MARC');
  v_series text := nullif(p_header->>'invoice_by_type','');
  v_export boolean;
  v_id bigint;
begin
  perform public._invoice_guard();
  if v_type not in ('Proforma','Taxable','Export') then raise exception 'Invalid invoice type'; end if;
  if v_by not in ('MARC','KNP','KNPM','KNPI','AC') then raise exception 'Invalid billing entity'; end if;
  if v_by in ('KNPM','KNPI') and coalesce(v_series,'') not in ('M','Q','Y','MISC') then
    raise exception 'Pick a series (M, Q, Y or MISC) for this entity'; end if;
  if v_by not in ('KNPM','KNPI') then v_series := null; end if;
  if (p_header->>'project_id') is null or not exists (select 1 from public.projects where id = (p_header->>'project_id')::bigint) then
    raise exception 'Project not found'; end if;
  v_export := v_type = 'Export';

  insert into public.invoices (project_id, invoice_no, invoice_type, invoice_by, invoice_by_type, invoice_date, place_of_supply,
      recipient_name, recipient_address, recipient_pan, recipient_gst, recipient_state_code,
      delivery_name, delivery_address, delivery_pan, delivery_gst, delivery_state_code,
      advance, discount, ope, currency_type, currency_ope, created_by, created_at)
  values ((p_header->>'project_id')::bigint, public.next_invoice_no(v_type, v_by, v_series), v_type, v_by, v_series,
      coalesce(nullif(p_header->>'invoice_date','')::date, (now() at time zone 'Asia/Kolkata')::date),
      case when v_export then '' else nullif(p_header->>'place_of_supply','') end,
      p_header->>'recipient_name', p_header->>'recipient_address', p_header->>'recipient_pan', p_header->>'recipient_gst',
      case when v_export then '' else p_header->>'recipient_state_code' end,
      p_header->>'delivery_name', p_header->>'delivery_address', p_header->>'delivery_pan', p_header->>'delivery_gst',
      case when v_export then '' else p_header->>'delivery_state_code' end,
      case when v_export then 0 else coalesce(nullif(p_header->>'advance','')::numeric, 0) end,
      0, coalesce(nullif(p_header->>'ope','')::numeric, 0),
      case when v_export then nullif(p_header->>'currency_type','') else null end,
      case when v_export then nullif(p_header->>'currency_ope','')::numeric else null end,
      auth.uid(), now())
  returning id into v_id;
  perform public._invoice_save_lines(v_id, p_lines);
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'invoice.create', 'invoices', v_id::text);
  return v_id;
end $$;

-- Edit keeps the number; only unconfirmed, live invoices.
create or replace function public.update_invoice(p_id bigint, p_header jsonb, p_lines jsonb)
returns void language plpgsql security definer set search_path = '' as $$
declare v public.invoices; v_export boolean;
begin
  perform public._invoice_guard();
  select * into v from public.invoices where id = p_id and deleted_at is null for update;
  if not found then raise exception 'Invoice not found'; end if;
  if v.confirmed then raise exception 'A confirmed invoice cannot be edited'; end if;
  v_export := v.invoice_type = 'Export';
  update public.invoices set
      invoice_date = coalesce(nullif(p_header->>'invoice_date','')::date, invoice_date),
      place_of_supply = case when v_export then '' else nullif(p_header->>'place_of_supply','') end,
      recipient_name = p_header->>'recipient_name', recipient_address = p_header->>'recipient_address',
      recipient_pan = p_header->>'recipient_pan', recipient_gst = p_header->>'recipient_gst',
      recipient_state_code = case when v_export then '' else p_header->>'recipient_state_code' end,
      delivery_name = p_header->>'delivery_name', delivery_address = p_header->>'delivery_address',
      delivery_pan = p_header->>'delivery_pan', delivery_gst = p_header->>'delivery_gst',
      delivery_state_code = case when v_export then '' else p_header->>'delivery_state_code' end,
      advance = case when v_export then 0 else coalesce(nullif(p_header->>'advance','')::numeric, 0) end,
      ope = coalesce(nullif(p_header->>'ope','')::numeric, 0),
      currency_type = case when v_export then nullif(p_header->>'currency_type','') else null end,
      currency_ope = case when v_export then nullif(p_header->>'currency_ope','')::numeric else null end
   where id = p_id;
  perform public._invoice_save_lines(p_id, p_lines);
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'invoice.update', 'invoices', p_id::text);
end $$;

-- Proforma -> new Taxable invoice (new number, dated today), original flagged converted.
create or replace function public.convert_to_tax_invoice(p_id bigint)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v public.invoices; v_new bigint;
begin
  perform public._invoice_guard();
  select * into v from public.invoices where id = p_id and deleted_at is null for update;
  if not found then raise exception 'Invoice not found'; end if;
  if v.invoice_type <> 'Proforma' then raise exception 'Only a proforma can be converted'; end if;
  if v.converted then raise exception 'This proforma was already converted'; end if;
  insert into public.invoices (project_id, invoice_no, invoice_type, invoice_by, invoice_by_type, invoice_date, place_of_supply,
      recipient_name, recipient_address, recipient_pan, recipient_gst, recipient_state_code,
      delivery_name, delivery_address, delivery_pan, delivery_gst, delivery_state_code,
      advance, discount, ope, created_by, created_at)
  values (v.project_id, public.next_invoice_no('Taxable', v.invoice_by, v.invoice_by_type), 'Taxable', v.invoice_by, v.invoice_by_type,
      (now() at time zone 'Asia/Kolkata')::date, v.place_of_supply,
      v.recipient_name, v.recipient_address, v.recipient_pan, v.recipient_gst, v.recipient_state_code,
      v.delivery_name, v.delivery_address, v.delivery_pan, v.delivery_gst, v.delivery_state_code,
      v.advance, 0, v.ope, auth.uid(), now())
  returning id into v_new;
  insert into public.invoice_lines (invoice_id, position, service_description, sac, taxable_value, rupee_value)
    select v_new, position, service_description, sac, taxable_value, rupee_value from public.invoice_lines where invoice_id = p_id;
  update public.invoices set converted = true where id = p_id;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'invoice.convert', 'invoices', p_id::text);
  return v_new;
end $$;

create or replace function public.confirm_invoice_payment(p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform public._invoice_guard();
  update public.invoices set confirmed = true, confirmed_by = auth.uid(), confirmed_at = now()
   where id = p_id and deleted_at is null and not confirmed;
  if not found then raise exception 'Invoice not found or already confirmed'; end if;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'invoice.confirm', 'invoices', p_id::text);
end $$;

create or replace function public.delete_invoice(p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform public._invoice_guard();
  update public.invoices set deleted_at = now(), deleted_by = auth.uid() where id = p_id and deleted_at is null;
  if not found then raise exception 'Invoice not found'; end if;
  insert into public.audit_log (actor_id, action, entity, entity_id) values (auth.uid(), 'invoice.delete', 'invoices', p_id::text);
end $$;

grant execute on function public.create_invoice(jsonb,jsonb), public.update_invoice(bigint,jsonb,jsonb),
  public.convert_to_tax_invoice(bigint), public.confirm_invoice_payment(bigint), public.delete_invoice(bigint) to authenticated;

-- Direct writes on invoices now go through the RPCs only.
drop policy if exists "invoices write" on public.invoices;
drop policy if exists "invoice_lines write" on public.invoice_lines;

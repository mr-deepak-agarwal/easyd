-- Easy D: foundation, people and HR.
-- Source of truth for the shape of the data: the production MariaDB dump (u601689158_marceasyd).
-- Legacy integer ids are preserved (identity "by default") so existing links, URLs and invoice
-- records keep working. The migration script resets each sequence after loading.

create type public.user_role as enum ('admin', 'bd', 'teamlead', 'teamlead2', 'employee');

create or replace function public.set_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

-- ---------------------------------------------------------------- departments
create table public.departments (
  id            bigint generated by default as identity primary key,
  name          text not null unique,
  active        boolean not null default true,
  has_sub       boolean not null default false
);

create table public.sub_departments (
  id            bigint generated by default as identity primary key,
  department_id bigint not null references public.departments(id),
  name          text not null,
  active        boolean not null default true
);

-- ------------------------------------------------------------------- profiles
-- One row per login. id = Supabase Auth user id. empid is the legacy login (an email address).
create table public.profiles (
  id                 uuid primary key references auth.users(id) on delete cascade,
  legacy_id          integer unique,
  empid              text not null unique,
  name               text not null,
  role               public.user_role not null default 'employee',
  active             boolean not null default true,   -- false = terminated / cannot log in
  currently_working_on text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create trigger profiles_updated before update on public.profiles
  for each row execute function public.set_updated_at();

-- Role helpers used by every RLS policy. SECURITY DEFINER so policies can read profiles
-- without recursing into profiles' own policies.
create or replace function public.auth_role() returns public.user_role
language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = auth.uid() and active
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(public.auth_role() = 'admin', false)
$$;

-- admin, bd, teamlead, teamlead2
create or replace function public.is_mgmt() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(public.auth_role() in ('admin','bd','teamlead','teamlead2'), false)
$$;

-- --------------------------------------------------------------- employee data
-- employee_detail has 314 rows but only some have logins, so profile_id is optional.
create table public.employee_details (
  id           bigint generated by default as identity primary key,
  legacy_id    integer unique,
  empid        text not null unique,
  profile_id   uuid unique references public.profiles(id) on delete set null,
  name         text not null,
  designation  text,
  email        text,
  category     text,
  grade        text,
  salary       numeric(12,2),
  cv_path      text,          -- Supabase Storage object path (bucket: staff)
  docs_path    text,          -- Supabase Storage object path (bucket: staff)
  address      text,
  contact      text,
  join_date    date,
  dob          date,
  bank         text,
  gender       text,
  department   text,          -- free text in the legacy data, kept as is
  supervisor   text,
  emp_code     text,
  created_at   timestamptz not null default now()
);

create table public.leave_quota (
  id           bigint generated by default as identity primary key,
  profile_id   uuid not null unique references public.profiles(id) on delete cascade,
  casual       numeric(5,1),
  privilege    numeric(5,1)
);

create table public.leave_applications (
  id           bigint generated by default as identity primary key,
  profile_id   uuid not null references public.profiles(id),
  leave_from   date not null,
  leave_to     date not null,
  applied_on   date,
  reason       text,
  leave_type   text not null,  -- e.g. 'CL Full Day', 'OD Half Day', 'Work From Home'
  num_days     numeric(4,1) not null default 1,
  status       text not null default 'pending' check (status in ('pending','approved','rejected')),
  changed_by   uuid references public.profiles(id),
  changed_at   timestamptz,
  created_at   timestamptz not null default now()
);
create index on public.leave_applications (profile_id, leave_from);
create index on public.leave_applications (status);

-- Replaces both attd_register (in/out times) and employee_attendance (daily status).
create table public.attendance (
  id           bigint generated by default as identity primary key,
  profile_id   uuid not null references public.profiles(id),
  work_date    date not null,
  in_time      time,
  out_time     time,
  status       text,
  added_by     uuid references public.profiles(id),
  created_at   timestamptz not null default now(),
  unique (profile_id, work_date)
);

create table public.holidays (
  id           bigint generated by default as identity primary key,
  holiday_date date not null unique,
  description  text not null
);

create table public.circulars (
  id           bigint generated by default as identity primary key,
  title        text not null,
  file_path    text not null,  -- Supabase Storage object path (bucket: circulars)
  entered_by   uuid references public.profiles(id),
  entered_on   date,
  active       boolean not null default true,
  deleted_by   uuid references public.profiles(id),
  deleted_at   timestamptz
);

create table public.salary_entries (
  id           bigint generated by default as identity primary key,
  profile_id   uuid not null references public.profiles(id),
  pay_type     text not null,
  pay_date     date,
  designation  text,
  bank_branch  text,
  amount       numeric(12,2) not null default 0,
  description  text,
  entered_on   date,
  entered_by   uuid references public.profiles(id)
);
create index on public.salary_entries (profile_id, pay_date);

create table public.incentives (
  id           bigint generated by default as identity primary key,
  profile_id   uuid not null references public.profiles(id),
  incentive_date date,
  reason       text,
  amount       numeric(12,2) not null
);

create table public.appraisals (
  id            bigint generated by default as identity primary key,
  profile_id    uuid references public.profiles(id),   -- employee being appraised
  project_name  text,
  firm_name     text,
  feedback      smallint not null default 0,
  owner         smallint not null default 0,
  formatting    smallint not null default 0,
  enthusiasm    smallint not null default 0,
  detail        smallint not null default 0,
  submitted_by  uuid references public.profiles(id),
  submitted_at  timestamptz,
  client_remarks text,
  admin_remark  text
);

-- "complaints" in the legacy schema; the UI calls it Suggestions.
create table public.suggestions (
  id           bigint generated by default as identity primary key,
  profile_id   uuid not null references public.profiles(id),
  body         text not null,
  created_at   timestamptz not null default now(),
  remarks      text not null default 'yet_to_answer',
  replied_by   uuid references public.profiles(id)
);

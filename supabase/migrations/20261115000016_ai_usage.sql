-- AI features: a log of usage so the app can enforce monthly caps. Writes only through log_ai_usage().
create table public.ai_usage (
  id            bigint generated by default as identity primary key,
  profile_id    uuid not null references public.profiles(id) on delete cascade,
  feature       text not null,
  input_tokens  integer not null default 0 check (input_tokens >= 0),
  output_tokens integer not null default 0 check (output_tokens >= 0),
  created_at    timestamptz not null default now()
);
create index on public.ai_usage (created_at);
create index on public.ai_usage (profile_id, created_at);
alter table public.ai_usage enable row level security;
grant select on public.ai_usage to authenticated;
create policy "ai usage read" on public.ai_usage for select to authenticated
  using (public.is_admin() or profile_id = auth.uid());

create or replace function public.log_ai_usage(p_feature text, p_input integer, p_output integer)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  insert into public.ai_usage (profile_id, feature, input_tokens, output_tokens)
  values (auth.uid(), left(coalesce(p_feature, 'other'), 40), greatest(coalesce(p_input, 0), 0), greatest(coalesce(p_output, 0), 0));
end $$;

-- Tokens used this calendar month (IST): everyone, and the caller.
create or replace function public.ai_usage_summary()
returns table (total_tokens bigint, my_tokens bigint) language sql security definer stable set search_path = '' as $$
  select coalesce(sum(input_tokens + output_tokens), 0)::bigint,
         coalesce(sum(input_tokens + output_tokens) filter (where profile_id = auth.uid()), 0)::bigint
    from public.ai_usage
   where created_at >= date_trunc('month', now() at time zone 'Asia/Kolkata') at time zone 'Asia/Kolkata';
$$;
grant execute on function public.log_ai_usage(text,integer,integer), public.ai_usage_summary() to authenticated;

-- Easy D: CRM, costing and projects.

-- ------------------------------------------------------------------------ CRM
create table public.clients (
  id           bigint generated by default as identity primary key,
  firm_name    text,
  designation  text,
  email        text,
  address      text,
  phone        text,
  sector       text,
  pan          text,
  gstin        text,
  state_code   text,
  priority     integer not null default 0,
  active       boolean not null default true,
  entered_by   uuid references public.profiles(id),
  entered_at   timestamptz
);
create index on public.clients (firm_name);

create table public.client_contacts (
  id           bigint generated by default as identity primary key,
  client_id    bigint not null references public.clients(id) on delete cascade,
  name         text not null,
  designation  text,
  email        text,
  phone        text,
  address      text,
  place        text
);
create index on public.client_contacts (client_id);

-- ---------------------------------------------------------------------- costing
create table public.costing_grades (
  id           bigint generated by default as identity primary key,
  grade        text not null,
  cost         numeric(12,2) not null,
  active       boolean not null default true,
  created_by   uuid references public.profiles(id),
  created_at   timestamptz
);

-- History of the overhead figure; the latest row is the current one.
create table public.overheads (
  id           bigint generated by default as identity primary key,
  cost         numeric(12,2) not null,
  created_by   uuid references public.profiles(id),
  created_at   timestamptz
);

-- ---------------------------------------------------------------------- projects
create table public.projects (
  id              bigint generated by default as identity primary key,
  name            text,
  client_id       bigint references public.clients(id),
  leader_id       uuid references public.profiles(id),
  description     text,
  start_date      date,
  end_date        date,
  status          text not null default 'pending' check (status in ('pending','approved','rejected','closed')),
  percent_complete numeric(5,2) not null default 0,
  num_hours       numeric(10,2),
  actual_end_at   timestamptz,
  closed_by       uuid references public.profiles(id),
  closing_reason  text,
  rating          text,
  final_report    boolean not null default false,
  final_payment   boolean not null default false,
  additional_work_required text,
  department_id   bigint references public.departments(id),
  sub_department_id bigint references public.sub_departments(id),
  project_type    text check (project_type in ('one time','monthly','quarterly','yearly')),
  recurring       boolean not null default false,
  approved_by     uuid references public.profiles(id),
  approved_at     timestamptz,
  rejected_by     uuid references public.profiles(id),
  rejected_at     timestamptz,
  created_by      uuid references public.profiles(id),
  created_at      timestamptz
);
create index on public.projects (client_id);
create index on public.projects (status);
create index on public.projects (leader_id);

-- Legacy projects.team_members was a comma-separated string (empty in production);
-- membership lives here.
create table public.project_team (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  member_type  text not null check (member_type in ('Lead','Associate')),
  member_id    uuid references public.profiles(id),
  member_name  text,
  num_hours    numeric(10,2),
  start_date   date,
  end_date     date,
  entry_by     uuid references public.profiles(id),
  entry_at     timestamptz
);
create index on public.project_team (project_id);
create index on public.project_team (member_id);

create table public.leads (
  id           bigint generated by default as identity primary key,
  name         text not null,
  client_id    bigint references public.clients(id),
  service      text,
  comments     text,
  source       text,
  cost_type    text check (cost_type in ('chargeable','nonchargeable')),   -- legacy "costradio"
  category     text,                                                       -- legacy "cat"
  lead_generator uuid references public.profiles(id),
  lead_handler uuid references public.profiles(id),
  status       text not null default 'pending' check (status in ('pending','approved','rejected')),
  reject_reason text,
  rejected_by  uuid references public.profiles(id),
  rejected_at  timestamptz,
  approved_by  uuid references public.profiles(id),
  approved_at  timestamptz,
  approved_project_id bigint references public.projects(id),
  entered_by   uuid references public.profiles(id),
  entered_at   timestamptz
);
create index on public.leads (client_id);
create index on public.leads (status);

create table public.project_costing (
  id              bigint generated by default as identity primary key,
  project_id      bigint references public.projects(id),
  lead_id         bigint references public.leads(id),
  client_id       bigint references public.clients(id),
  grade_label     text not null,
  grade           text not null,
  num_employees   integer not null default 0,
  total_hours     numeric(10,2) not null default 0,
  overheads       numeric(12,2) not null default 0,
  multiply_factor numeric(8,3) not null default 0,
  total_cost      numeric(14,2) not null default 0,
  actual_total_cost numeric(14,2) not null default 0,
  renegotiated_cost numeric(14,2),
  active          boolean not null default true,
  added_by        uuid references public.profiles(id),
  added_at        timestamptz,
  approved_reason text,
  approved_by     uuid references public.profiles(id),
  approved_at     timestamptz,
  rejected_reason text,
  rejected_by     uuid references public.profiles(id),
  rejected_at     timestamptz
);
create index on public.project_costing (project_id);
create index on public.project_costing (lead_id);

-- Pre-project meetings (module M9). Empty in production but the screens exist.
create table public.pre_projects (
  id             bigint generated by default as identity primary key,
  entered_by     uuid references public.profiles(id),
  firm_name      text,
  firm_address   text,
  firm_sector    text,
  meeting_reason text,
  project_name   text,
  description    text,
  conclusion     text,
  status         text not null default 'Pending',
  proposal_team  text,
  proposal_doc   text,
  keywords       text,
  remarks        text,
  created_at     timestamptz not null default now()
);

-- --------------------------------------------------------- project workspace
create table public.project_milestones (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  milestone    text not null,
  percentage   integer not null check (percentage between 0 and 100),
  start_date   date,
  end_date     date,
  complete     boolean not null default false,
  created_by   uuid references public.profiles(id),
  created_at   timestamptz,
  updated_by   uuid references public.profiles(id),
  updated_at   timestamptz
);
create index on public.project_milestones (project_id);

-- History of completion-percentage updates (legacy project_completion).
create table public.project_completions (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  milestone_id bigint references public.project_milestones(id) on delete set null,
  percent_complete integer not null,
  reason       text,
  entry_by     uuid references public.profiles(id),
  entry_at     timestamptz
);
create index on public.project_completions (project_id);

create table public.project_documents (
  id           bigint generated by default as identity primary key,
  project_id   bigint references public.projects(id) on delete cascade,
  lead_id      bigint references public.leads(id) on delete cascade,
  file_path    text,             -- Supabase Storage object path (bucket: documents)
  description  text,
  entry_by     uuid references public.profiles(id),
  entry_at     timestamptz
);
create index on public.project_documents (project_id);

create table public.project_proposals (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  file_path    text not null,
  description  text,
  entry_by     uuid references public.profiles(id),
  entry_at     timestamptz
);
create index on public.project_proposals (project_id);

create table public.project_meetings (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  members      text[] not null default '{}',   -- profile ids as text; legacy was a comma list
  agenda       text,
  meeting_at   timestamptz,
  conclusion   text,
  created_by   uuid references public.profiles(id),
  created_at   timestamptz
);
create index on public.project_meetings (project_id);

create table public.project_forum_chats (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  user_id      uuid references public.profiles(id),
  message      text not null,
  created_at   timestamptz not null default now()
);
create index on public.project_forum_chats (project_id, created_at);

-- CRM follow-ups: tied to a client, lead or project (legacy used 0 for "none").
create table public.followups (
  id            bigint generated by default as identity primary key,
  client_id     bigint references public.clients(id),
  lead_id       bigint references public.leads(id),
  project_id    bigint references public.projects(id),
  prospect_name text,
  reason        text,
  reply         text,
  description   text,
  next_followup_on date,
  file_path     text,
  file_description text,
  entered_by    uuid references public.profiles(id),
  entered_at    timestamptz
);
create index on public.followups (client_id);
create index on public.followups (lead_id);

